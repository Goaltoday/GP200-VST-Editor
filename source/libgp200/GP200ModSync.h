#pragma once

#include <JuceHeader.h>
#include <cstdint>
#include <memory>
#include "GP200EffectParamDatabase.h"

namespace gp200
{
// Immutable after import. Owning names keep parameter C strings valid.
struct GP200EffectBankEntry
{
    juce::uint32 destinationEffectId{0}, sourceEffectId{0};
    juce::String destinationModule, sourceModule, displayName, profile;
    std::array<juce::String, effectParamCount> parameterNames;
    std::array<GP200EffectParamInfo, effectParamCount> parameters;
    std::array<int, effectParamCount> sourceParameterIndices{};
    GP200EffectParamSet parameterSet;
};

class GP200ModSync final
{
  public:
    // Explicit I/O entry points; getters below only consult memory.
    static void reloadIfChanged ();
    static void pollForChanges ();
    static bool hasEffectBank ();
    static std::shared_ptr<const GP200EffectBankEntry> findEffectBankEntry (
        juce::uint32 effectId, const juce::String& moduleName);
    static juce::String getEffectBankStatus ();
    static juce::File getEffectBankFile ();
    static bool replacePreBankFromDevice (const juce::var& snapshot);
    static bool replaceFromDevice (const juce::var& snapshot, int userIRSamples);
    static std::uint64_t getRevision ();

    // NAM profiles come from GP200_MOD_SYNC.json; MS11 cannot discover them.
    static bool canUseNamHot (int zeroBasedFactoryAmpIndex);
    static bool removeNamAmpOverride (juce::uint32 effectId);
    static bool isNamAmp (juce::uint32 effectId);
    static bool canWriteFactoryClo (int zeroBasedFactoryAmpIndex);
    static juce::String getNamMetadataStatus ();
    static bool isCustomCloAmp (juce::uint32 effectId);
    static juce::String getDisplayName (juce::uint32 effectId);
    static juce::String getSourceFile (juce::uint32 effectId);
    static juce::String getDescription (juce::uint32 effectId);

    // PRE configurable mapping generated by the firmware HTML. These methods
    // are module-specific so duplicated PRE/DST IDs keep their stock meaning
    // outside PRE.
    static juce::uint32 getPreBankSourceEffectId (juce::uint32 preEffectId);
    static juce::String getPreBankDisplayName (juce::uint32 preEffectId);
    static juce::String getPreBankSourceModule (juce::uint32 preEffectId);
    static juce::String getPreBankDescription (juce::uint32 preEffectId);
    static juce::File getPreBankFile ();

    // Static WAH package mapping generated by the firmware HTML. The physical
    // WAH ID stays unchanged while names and parameters come from a MOD effect.
    static juce::uint32 getWahConfigSourceEffectId (juce::uint32 wahEffectId);
    static juce::String getWahConfigDisplayName (juce::uint32 wahEffectId);
    static juce::String getWahConfigSourceModule (juce::uint32 wahEffectId);
    static juce::String getWahConfigDescription (juce::uint32 wahEffectId);
    static juce::File getWahConfigFile ();

    static bool recordNamAmpOverride (juce::uint32 effectId, const juce::String& displayName, const juce::String& sourceFile);
    static void recordFactoryAmpOverride (juce::uint32 effectId,
                                          const juce::String& displayName,
                                          const juce::String& sourceFile);
    static void recordFactoryCabOverride (juce::uint32 effectId,
                                          const juce::String& displayName,
                                          const juce::String& sourceFile);

    static juce::File getManifestFile ();
};
} // namespace gp200
